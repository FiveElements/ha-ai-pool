#!/usr/bin/env bash
# Regenerate the hash-locked requirement files CI installs with --require-hashes.
#
#   scripts/lock.sh                 # lint, docs, fuzz + the harness in requirements-test.txt
#   scripts/lock.sh 0.13.363 0.13.400   # one test lock per harness (one per CI matrix row)
#
# Runs in the CI image so markers and wheels resolve for Linux, not the host.
set -euo pipefail

if [ "${AI_POOL_LOCK_IN_DOCKER:-}" != 1 ]; then
  cd "$(dirname "$0")/.."
  exec docker run --rm -e AI_POOL_LOCK_IN_DOCKER=1 \
    -v "$PWD:/src" -v ha-ai-pool-pip:/root/.cache/pip -w /src \
    python:3.14-bookworm bash scripts/lock.sh "$@"
fi

pip install -q pip-tools==7.6.2
compile() {
  pip-compile -q --generate-hashes --allow-unsafe --strip-extras \
    --output-file="$2" "$1"
}

for name in lint docs fuzz; do
  compile "requirements-$name.in" "requirements-$name.txt"
done

pin() { sed -n "s/^$1==//p" requirements-test.txt; }
mypy=$(pin mypy)
harnesses=("$@")
[ ${#harnesses[@]} -gt 0 ] || harnesses=("$(pin pytest-homeassistant-custom-component)")

mkdir -p requirements-ci
for harness in "${harnesses[@]}"; do
  # The components' requirements are read from the manifests this harness
  # installs, so each harness gets its own lock.
  python -m venv /tmp/harness-"$harness"
  /tmp/harness-"$harness"/bin/pip install -q \
    "pytest-homeassistant-custom-component==$harness"
  {
    echo "# Generated by scripts/lock.sh; edit that script, not this file."
    echo "pytest-homeassistant-custom-component==$harness"
    echo "mypy==$mypy"
    /tmp/harness-"$harness"/bin/python scripts/component_requirements.py
  } > "requirements-ci/harness-$harness.in"
  compile "requirements-ci/harness-$harness.in" "requirements-ci/harness-$harness.txt"
done
